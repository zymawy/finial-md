const shuffleArray = (array) => {
    return array.sort(() => Math.random() - 0.5);
  };

  export const getRandomPerfumes = (count) => {
    const shuffled = shuffleArray([...PERUMES]);
    return shuffled.slice(0, count);
  };


  export const getPerfumesByReference = (reference_type, reference_id) => {
    let filteredPerfumes = [];
    if (reference_type === "brand") {
        filteredPerfumes = PERUMES.filter(perfume => perfume.brand_id === reference_id);
    } else if (reference_type === "category") {
        filteredPerfumes = PERUMES.filter(perfume =>
            perfume.categories.some(category => category.id === reference_id)
        );
    } else {
      filteredPerfumes = PERUMES;
    }

    return { data: filteredPerfumes, error: "", loading: false, isBanner: false };
};
